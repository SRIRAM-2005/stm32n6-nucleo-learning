/* printf() -> _write() in syscalls.c -> __io_putchar() -> USART1 -> ST-LINK VCP */
int __io_putchar(int ch)
{
  uint8_t c = (uint8_t)ch;
  (void)HAL_UART_Transmit(&huart1, &c, 1U, HAL_MAX_DELAY);
  return ch;
}

static void LED_Set(GPIO_TypeDef *port, uint16_t pin, uint8_t on)
{
  HAL_GPIO_WritePin(port, pin, on ? LED_ON_LEVEL : LED_OFF_LEVEL);
}

/* Exercise 1: blocking blink. HAL_Delay() busy-waits on the SysTick tick. */
static void Run_Exercise1(void)
{
  uint32_t count = 0U;
  while (1)
  {
    LED_Set(LED_RED_GPIO_Port, LED_RED_Pin, 1U);
    HAL_Delay(250);
    LED_Set(LED_RED_GPIO_Port, LED_RED_Pin, 0U);
    HAL_Delay(250);
    printf("blink %lu  tick=%lu ms\r\n",
           (unsigned long)count++, (unsigned long)HAL_GetTick());
  }
}

/* Exercise 2: polling + software edge detection + debounce,
 * with a non-blocking heartbeat on the red LED. */
static void Run_Exercise2(void)
{
  GPIO_PinState prev = HAL_GPIO_ReadPin(USER_BTN_GPIO_Port, USER_BTN_Pin);
  uint32_t last_change = HAL_GetTick();
  uint32_t last_blink  = HAL_GetTick();
  uint8_t  green = 0U, red = 0U;
  uint32_t presses = 0U;

  while (1)
  {
    uint32_t now = HAL_GetTick();
    GPIO_PinState cur = HAL_GPIO_ReadPin(USER_BTN_GPIO_Port, USER_BTN_Pin);

    if ((cur != prev) && ((now - last_change) >= DEBOUNCE_MS))
    {
      last_change = now;
      if (cur == GPIO_PIN_SET)               /* B1 reads HIGH when pressed */
      {
        green ^= 1U;
        LED_Set(LED_GREEN_GPIO_Port, LED_GREEN_Pin, green);
        printf("[poll] press %lu, green=%u\r\n",
               (unsigned long)++presses, green);
      }
      prev = cur;
    }

    if ((now - last_blink) >= 500U)
    {
      last_blink = now;
      red ^= 1U;
      LED_Set(LED_RED_GPIO_Port, LED_RED_Pin, red);
    }
  }
}

/* Exercise 3: EXTI interrupt only sets a flag; main loop does the work. */
static void Run_Exercise3(void)
{
  uint32_t last_blink = HAL_GetTick();
  uint8_t  green = 0U, red = 0U;
  uint32_t presses = 0U;

  while (1)
  {
    if (g_button_event)
    {
      g_button_event = 0U;
      green ^= 1U;
      LED_Set(LED_GREEN_GPIO_Port, LED_GREEN_Pin, green);
      printf("[irq] press %lu, green=%u\r\n",
             (unsigned long)++presses, green);
    }

    uint32_t now = HAL_GetTick();
    if ((now - last_blink) >= 500U)
    {
      last_blink = now;
      red ^= 1U;
      LED_Set(LED_RED_GPIO_Port, LED_RED_Pin, red);
    }
  }
}

/* Called from EXTI13_IRQHandler (stm32n6xx_it.c) -> HAL_GPIO_EXTI_IRQHandler().
 * STM32N6 HAL has separate rising/falling callbacks. Keep ISRs short. */
void HAL_GPIO_EXTI_Rising_Callback(uint16_t GPIO_Pin)
{
  if (GPIO_Pin == USER_BTN_Pin)
  {
    uint32_t now = HAL_GetTick();
    if ((now - g_last_irq_tick) >= DEBOUNCE_MS)
    {
      g_last_irq_tick = now;
      g_button_event  = 1U;
    }
  }
}
